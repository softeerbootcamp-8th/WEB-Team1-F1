package com.softeer.race.auctionroom.application;

/**
 * 경매방 현황을 받아가는 열린 구독
 */
public interface RoomSubscription {

    /**
     * 한 건 맡긴다, 기다리지 않고 곧바로 돌아오며 낡은 것과 밀려서 못 보낸 것은 버린다
     */
    // 기다리면 느린 사람 하나가 뒤에 선 전원과 입찰한 사람의 응답을 함께 세운다, 실측으로 확인했다
    // 버려도 되는 것은 현황이 그때의 전부를 싣고 있어서다, 종류마다 최신 한 건이면 화면이 정확하다
    void send(RoomMessage message);

    /**
     * 살아 있는지 확인만 하는 신호, 현황을 담지 않고 맡기기만 하고 돌아온다
     */
    void ping();

    /**
     * 서버가 연결을 끝낸다, 맡겨 둔 것을 다 내보낸 뒤에 실제로 끝나고 이 호출은 기다리지 않는다
     */
    // 밀린 것보다 먼저 끝내면 마감 현황이 사라진다, 방송 직후에 방을 끊으므로 그 한 건이 결과 화면의 근거다
    // 던지지 않는 것도 계약이다, 그래야 채널이 방어 없이 방 하나를 통째로 끊을 수 있다
    void close();

    /**
     * 아직 살아 있는지, 끝내기를 맡긴 순간부터 거짓이라 실제로 끝나기 전에도 새 현황을 받지 않는다
     */
    boolean isOpen();

    /**
     * 이 구독을 연 사람, 같은 사람이 연 창들을 하나로 묶는 데만 쓴다
     */
    // 방송에 싣지 않는다, 그것을 지키는 것은 이 주석이 아니라 RoomStreamIntegrationTest 의 누출 단정이다
    long viewerId();
}
