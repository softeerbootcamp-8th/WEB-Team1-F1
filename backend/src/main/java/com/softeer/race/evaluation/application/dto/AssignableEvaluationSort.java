package com.softeer.race.evaluation.application.dto;

/**
 * 배정 대기 목록을 어떤 순서로 볼지.
 * <p>
 * 정렬이 곧 커서다. 이어 읽는 지점을 정렬 키의 값으로 표현하므로, 정렬이 바뀌면 커서에 담기는
 * 값의 구성까지 함께 바뀐다. 그래서 정렬을 목록의 표시 옵션이 아니라 조회 계약의 일부로 둔다.
 */
public enum AssignableEvaluationSort {

    /**
     * 방문일이 임박한 순서. 기본값이다.
     * <p>
     * 평가사가 목록에서 판단하는 것은 "언제 어디를 가야 하는가"이고, 지나가 버리면 늦는 쪽이
     * 방문일이다. 접수가 언제였는지는 그다음 문제라 기본 정렬 자리를 내주지 않는다.
     */
    VISIT_DATE,

    /**
     * 접수가 최근인 순서.
     * <p>
     * 방금 들어온 신청을 먼저 보고 싶을 때 쓴다. 방문일 순으로는 새 신청이 목록 중간에 꽂혀
     * 어디에 생겼는지 찾을 수 없다.
     */
    LATEST
}
