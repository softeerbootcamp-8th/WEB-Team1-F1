package com.softeer.race.auth.domain;

import com.softeer.race.user.domain.Role;

/**
 * 인증을 통과한 요청 주체. 원시 long이 아니라 타입으로 감싸는 이유는 두 가지다.
 * 인자 리졸버가 애너테이션과 타입 두 조건을 함께 요구해 다른 long 파라미터를 실수로 가로채지 않고,
 * 나중에 필드를 늘려도 호출부 시그니처가 바뀌지 않는다.
 * <p>
 * <b>역할은 로그인 시점에 세션으로 복사된다.</b> 인증이 회원 조회 없이 세션 하나로 끝나는 대신,
 * 세션이 살아 있는 동안 역할이 바뀌어도 최대 세션 TTL만큼 반영되지 않는다.
 * <p>
 * 지금은 역할을 바꾸는 경로가 없어서(가입 시 정해지고, 평가사는 서비스가 직접 심는다) 드러날 일이
 * 없다. 역할 변경 기능을 들일 때는 그 회원의 세션을 함께 폐기해야 하고, 회원 하나가 여러 세션을
 * 가질 수 있으므로 회원 -> 세션 역인덱스를 같이 만들어야 한다.
 */
public record AuthenticatedUser(long id, Role role) {
}
