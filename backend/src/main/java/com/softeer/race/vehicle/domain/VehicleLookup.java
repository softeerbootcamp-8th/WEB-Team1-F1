package com.softeer.race.vehicle.domain;

import java.util.Optional;
/**
 * 번호판과 소유자명을 받아 차량 제원을 찾아 주는 차량 조회기.
 *
 * <p>지금은 자체 보유 카탈로그를 보지만 외부 차량 정보 서비스로 교체될 자리라,
 * 호출자는 구현체가 아니라 이 인터페이스에만 의존한다.
 */
public interface VehicleLookup {
    /**
     * 번호판과 소유자명이 모두 맞는 차량의 제원을 돌려준다. 하나라도 어긋나면 빈 값이다.
     *
     * <p>소유자명은 인증 수단이 아니라 조회 입력값이다. 비회원도, 자기 차가 아니어도 두 값만 알면 조회된다.
     * 다만 번호판만으로는 찾을 수 없어야 한다 — 번호판을 바꿔 넣어보며 소유자명을 역으로 알아내는 걸 막는다.
     *
     * <p>못 찾은 이유(미등록 / 소유자명 불일치)는 구분해 돌려주지 않는다.
     * 구분할 수 있으면 호출자가 그대로 응답에 흘릴 수 있고, 그 순간 위 보호가 무너진다.
     *
     * <p>실패를 예외가 아니라 빈 값으로 내는 이유는 응답이 호출자마다 다르기 때문이다.
     * 시세 조회는 404, 판매 신청은 등록 거부라 조회기가 에러 코드를 정할 수 없다.
     */
    Optional<VehicleSpec> find(String plateNumber, String ownerName);
}
