package com.softeer.race.vehicle.domain;

/**
 * 평가사가 방문해 확인한 것을 차량에 매기는 키워드. 한 차량에 여러 개가 붙는다.
 * <p>
 * <b>사고 등급은 외판 검사 기준이다.</b> {@link #ACCIDENT_FREE}는 외부패널에 교환도 판금도 없다는
 * 뜻이고 {@link #MINOR_EXCHANGE}는 교환이나 판금은 있으나 프레임이 정상이라는 뜻이다. 보험처리
 * 이력을 조회해 판정하는 것이 아니라 평가사가 도막을 재고 하부를 들여다본 결과다 — 이력 조회가
 * 붙는 날 판정 근거가 늘어나면 그때 이 두 값의 기준을 다시 잡는다.
 * <p>
 * 둘은 실제로 상호 배타지만 그 규칙을 강제하지 않는다. 둘 다 매겨진 차량이 나올 수 있다.
 * <p>
 * <b>선언 순서가 표시 순서다.</b> 목록 카드는 좁아서 앞의 두세 개만 보이므로 값에 영향이 큰 것이
 * 앞에 온다. 평가사가 고른 순서를 쓰지 않는 이유는 같은 조합이 차량마다 다른 순서로 보이기
 * 때문이다 — {@code VehicleImage.sortOrder}는 첫 장이 대표 이미지가 되어 순서에 의미가 있지만
 * 키워드는 없다.
 * <p>
 * 표시 문구는 담지 않는다. {@link FuelType}·{@link Manufacturer}와 같이 코드만 내리고 화면 문구는
 * 클라이언트가 매핑한다.
 * <p>
 * <b>조회해야 알 수 있는 것은 넣지 않는다.</b> 소유자 변경 이력이나 보험처리 건수는 평가사가
 * 현장에서 확인할 방법이 없어, 목록에 있으면 근거 없이 체크되거나 늘 비어 있게 된다. 등록원부와
 * 보험이력을 실제로 조회하는 경로가 생길 때 그 결과에서 파생시킬 일이다.
 * <p>
 * <b>이미 다른 컬럼이 말해주는 것도 두지 않는다.</b> 저주행 같은 값을 넣으면 {@code Vehicle.mileage}가
 * 20만km인데 그 키워드가 붙은 차량이 만들어지고, 둘 중 어느 쪽이 진짜인지 알 방법이 없다.
 * 연식도 같은 이유로 없다.
 */
public enum VehicleKeyword {

    /** 완전무사고. 외부패널에 교환도 판금도 없다 */
    ACCIDENT_FREE,

    /** 단순교환 무사고. 교환이나 판금은 있으나 프레임은 정상이다 */
    MINOR_EXCHANGE,

    /** 누유가 없다 */
    NO_LEAK,

    /** 파손된 부위가 없다 */
    NO_DAMAGE,

    /** 하부에 부식이나 손상이 없다 */
    UNDERBODY_INTACT,

    /** 타이어 잔량이 충분하다 */
    GOOD_TIRE,

    /** 실내 상태가 깨끗하다 */
    CLEAN_INTERIOR
}
