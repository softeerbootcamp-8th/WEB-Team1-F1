package com.softeer.race.storage.domain;

/**
 * 파일 저장소. 서버는 서명된 주소만 발급하고 파일 자체는 다루지 않는다.
 * <p>
 * 한 번에 여러 장을 올리고 현장에서 찍은 원본은 장당 몇 MB다. 진단서 스캔은 그보다 크다. 그
 * 바이트가 서버를 통과하면 업로드가 끝날 때까지 요청 스레드가 묶이는데, 같은 서버가 경매방 SSE
 * 구독을 들고 있어 실시간 쪽이 함께 느려진다.
 * <p>
 * 인터페이스로 두는 이유는 저장소를 바꿀 수 있어서가 아니라, 이게 없으면 서비스 테스트가 실제
 * 자격 증명을 요구하기 때문이다.
 */
public interface FileStorage {

    /**
     * 업로드 한 건에 대한 서명된 주소를 발급한다. 키는 구현체가 정한다.
     *
     * @param contentLength 업로드할 파일의 정확한 바이트 수. 서명에 포함되므로 실제와 다르면 거부된다
     */
    PresignedUpload presign(UploadContentType contentType, long contentLength);

    /**
     * 우리가 발급한 <b>그 종류의</b> 주소인지 판정한다.
     * <p>
     * 클라이언트가 돌려준 URL을 저장하기 전에 <b>반드시</b> 통과시켜야 한다. 그냥 믿으면
     * 로그인한 사용자가 임의의 외부 주소를 차량 이미지로 박아 넣을 수 있다.
     * <p>
     * 종류를 함께 받는 이유는 "우리가 발급했는가"만으로는 부족해졌기 때문이다. 진단서 PDF도 우리가
     * 발급한 주소라, 그 판정만 하면 <b>PDF가 차량 사진 자리에 그대로 등록된다.</b> 호출자가 기대하는
     * 종류를 밝히게 해서 사진 자리에는 사진만, 문서 자리에는 문서만 들어가게 한다.
     * <p>
     * 이 판정이 저장소 쪽에 있는 이유는 조회용 주소를 만드는 곳이 여기이기 때문이다.
     * 판정 규칙과 생성 규칙이 갈라지면 방금 발급한 주소가 검증에서 떨어지는 일이 생긴다.
     */
    boolean isManagedUrl(String fileUrl, FileCategory category);
}
